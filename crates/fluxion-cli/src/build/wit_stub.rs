/// Generate a Python stub file from `wit/task.wit` for use with `componentize-py`.
///
/// The generated `task.py` contains:
/// - `TaskInput` / `TaskOutput` dataclasses matching the WIT records
/// - A skeleton `Processor` class implementing the `process` export
///
/// Kebab-case WIT field names are converted to snake_case Python identifiers.
pub fn generate(wit_source: &str) -> String {
    // Extract field names from WIT records.
    let input_fields = parse_record_fields(wit_source, "task-input");
    let output_fields = parse_record_fields(wit_source, "task-output");

    let input_dataclass = render_dataclass("TaskInput", &input_fields);
    let output_dataclass = render_dataclass("TaskOutput", &output_fields);

    format!(
        r#"# Auto-generated by fluxion — do not edit manually.
# Implements the `processor` WIT interface for componentize-py.
from __future__ import annotations
from dataclasses import dataclass, field
from typing import List, Tuple


{input_dc}

{output_dc}


class Processor:
    """Implement this class to handle task execution."""

    def process(self, input: TaskInput) -> TaskOutput:
        raise NotImplementedError("Override Processor.process() in your component")
"#,
        input_dc = input_dataclass,
        output_dc = output_dataclass,
    )
}

/// Parse field definitions from a named WIT record block.
///
/// Returns `(python_name, python_type)` pairs. Kebab-case names are
/// converted to snake_case. Only the WIT types used by `task.wit` are
/// handled; unknown types fall back to `object`.
fn parse_record_fields(wit: &str, record_name: &str) -> Vec<(String, String)> {
    // Find the record block: `record <name> { … }`.
    let marker = format!("record {record_name}");
    let start = match wit.find(marker.as_str()) {
        Some(pos) => pos,
        None => return vec![],
    };
    let brace_open = match wit[start..].find('{') {
        Some(pos) => start + pos + 1,
        None => return vec![],
    };
    let brace_close = match wit[brace_open..].find('}') {
        Some(pos) => brace_open + pos,
        None => return vec![],
    };

    wit[brace_open..brace_close]
        .lines()
        .filter_map(|line| {
            let line = line.trim().trim_end_matches(',');
            let colon = line.find(':')?;
            let wit_name = line[..colon].trim();
            let wit_type = line[colon + 1..].trim();
            let py_name = kebab_to_snake(wit_name);
            let py_type = wit_type_to_python(wit_type);
            if py_name.is_empty() {
                None
            } else {
                Some((py_name, py_type))
            }
        })
        .collect()
}

fn kebab_to_snake(name: &str) -> String {
    name.replace('-', "_")
}

fn wit_type_to_python(wit_type: &str) -> String {
    let t = wit_type.trim();
    if t == "list<u8>" {
        "List[int]".to_string()
    } else if t == "list<tuple<string, string>>" {
        "List[Tuple[str, str]]".to_string()
    } else if t == "string" {
        "str".to_string()
    } else if t.starts_with("list<") {
        "List[object]".to_string()
    } else {
        "object".to_string()
    }
}

/// Render a `@dataclass` definition for a record.
fn render_dataclass(class_name: &str, fields: &[(String, String)]) -> String {
    let mut lines = vec!["@dataclass".to_string(), format!("class {class_name}:")];
    if fields.is_empty() {
        lines.push("    pass".to_string());
    } else {
        for (name, ty) in fields {
            let default = if ty.starts_with("List") {
                format!("    {name}: {ty} = field(default_factory=list)")
            } else {
                format!("    {name}: {ty} = None")
            };
            lines.push(default);
        }
    }
    lines.join("\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE_WIT: &str = r#"
        interface processor {
            record task-input {
                content:  list<u8>,
                metadata: list<tuple<string, string>>,
            }
            record task-output {
                content:  list<u8>,
                metadata: list<tuple<string, string>>,
            }
            process: func(input: task-input) -> result<task-output, string>;
        }
    "#;

    #[test]
    fn generates_task_input_dataclass() {
        let out = generate(SAMPLE_WIT);
        assert!(out.contains("class TaskInput"), "missing TaskInput class");
        assert!(out.contains("content: List[int]"), "missing content field");
        assert!(
            out.contains("metadata: List[Tuple[str, str]]"),
            "missing metadata field"
        );
    }

    #[test]
    fn generates_task_output_dataclass() {
        let out = generate(SAMPLE_WIT);
        assert!(out.contains("class TaskOutput"), "missing TaskOutput class");
    }

    #[test]
    fn generates_processor_skeleton() {
        let out = generate(SAMPLE_WIT);
        assert!(out.contains("class Processor:"), "missing Processor class");
        assert!(
            out.contains("def process(self, input: TaskInput) -> TaskOutput:"),
            "missing process method"
        );
    }

    #[test]
    fn kebab_case_converted_to_snake_case() {
        let wit = r#"
            interface processor {
                record task-input { some-field: string, }
                record task-output { }
                process: func(input: task-input) -> result<task-output, string>;
            }
        "#;
        let out = generate(wit);
        assert!(
            out.contains("some_field"),
            "kebab → snake conversion failed"
        );
    }

    #[test]
    fn empty_record_generates_pass() {
        let wit = r#"
            interface processor {
                record task-input { }
                record task-output { }
                process: func(input: task-input) -> result<task-output, string>;
            }
        "#;
        let out = generate(wit);
        assert!(out.contains("pass"), "empty record should emit pass");
    }

    #[test]
    fn unknown_record_returns_empty_fields() {
        let fields = parse_record_fields(SAMPLE_WIT, "nonexistent-record");
        assert!(fields.is_empty());
    }
}
