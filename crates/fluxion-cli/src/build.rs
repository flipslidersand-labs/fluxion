///
/// The stub imports the generated bindings and provides a skeleton `process`
/// function that the user fills in.
pub fn generate_python_stub(output_path: &Path) -> Result<()> {
    const STUB: &str = r#"# Auto-generated by `fluxion build python --init`
# Implements the fluxion:task/processor interface.
#
# The `process` function receives:
#   input.content   — bytes payload from the previous job or workflow input
#   input.metadata  — list of (key, value) string pairs
#
# Return a TaskOutput with your result bytes and optional metadata.

from task_component.imports import TaskInput, TaskOutput


def process(input: TaskInput) -> TaskOutput:
    # Decode input, do work, return output.
    data = bytes(input.content).decode("utf-8", errors="replace")
    result = data  # TODO: replace with real logic
    return TaskOutput(
        content=list(result.encode("utf-8")),
        metadata=[("source", "python-component")],
    )
"#;

    std::fs::write(output_path, STUB)
        .with_context(|| format!("cannot write stub to {}", output_path.display()))?;
    println!("✓ Generated stub: {}", output_path.display());
    Ok(())
}

/// Infer the output path from the script path: `hello.py` → `hello.wasm`.
pub fn default_output(script: &Path) -> PathBuf {
    script.with_extension("wasm")
}
